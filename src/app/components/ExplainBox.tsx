'use client';

import React, { useState } from 'react';
import { Sparkles, RefreshCw, Globe, CheckCircle, ShieldCheck } from 'lucide-react';
import { api } from '@/lib/client';
import { ExplainResult } from '@/lib/gemma';

interface ExplainBoxProps {
  medicineId: string;
  district: string;
  alertId?: string;
  initialExplanation?: string;
  initialLang?: 'en' | 'si' | 'ta';
}

export function ExplainBox({
  medicineId,
  district,
  alertId,
  initialExplanation,
  initialLang = 'en',
}: ExplainBoxProps) {
  const [lang, setLang] = useState<'en' | 'si' | 'ta'>(initialLang);
  const [explanation, setExplanation] = useState<string | null>(initialExplanation || null);
  const [loading, setLoading] = useState(false);
  const [provenance, setProvenance] = useState<string | null>(null);
  const [usedTool, setUsedTool] = useState(true);

  const fetchExplanation = async (targetLang = lang, forceRefresh = false) => {
    setLoading(true);
    const res = await api<ExplainResult>('/api/ai/explain', {
      method: 'POST',
      body: JSON.stringify({
        medicineId,
        district,
        language: targetLang,
        alertId,
        refresh: forceRefresh,
      }),
    });

    setLoading(false);
    if (res.data) {
      setExplanation(res.data.explanation);
      setProvenance(res.data.provenance);
      setUsedTool(res.data.usedTool);
    }
  };

  const handleLangChange = (newLang: 'en' | 'si' | 'ta') => {
    setLang(newLang);
    fetchExplanation(newLang, false);
  };

  return (
    <div className="bg-sky-50/60 border border-sky-200 rounded-lg p-4 sm:p-5 text-sm space-y-3">
      <div className="flex flex-wrap items-center justify-between gap-3 pb-2 border-b border-sky-100">
        <div className="flex items-center gap-2">
          <div className="w-7 h-7 rounded-md bg-[#005691] flex items-center justify-center text-white">
            <Sparkles className="w-4 h-4" />
          </div>
          <div>
            <h4 className="font-bold text-slate-900 text-sm">
              Gemma 4 Shortage Intelligence Brief
            </h4>
            <span className="text-[11px] text-slate-500">
              Deterministic synthesis via function calling
            </span>
          </div>
        </div>

        {/* Language selector & refresh */}
        <div className="flex items-center gap-2">
          <div className="flex items-center bg-white rounded-md border border-slate-200 p-0.5 text-xs font-semibold">
            <button
              onClick={() => handleLangChange('en')}
              className={`px-2 py-1 rounded transition ${
                lang === 'en' ? 'bg-[#005691] text-white' : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              EN
            </button>
            <button
              onClick={() => handleLangChange('si')}
              className={`px-2 py-1 rounded transition ${
                lang === 'si' ? 'bg-[#005691] text-white' : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              සිංහල
            </button>
            <button
              onClick={() => handleLangChange('ta')}
              className={`px-2 py-1 rounded transition ${
                lang === 'ta' ? 'bg-[#005691] text-white' : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              தமிழ்
            </button>
          </div>

          <button
            onClick={() => fetchExplanation(lang, true)}
            disabled={loading}
            className="p-1.5 rounded-md text-slate-600 hover:text-slate-900 hover:bg-sky-100/60 transition disabled:opacity-50"
            title="Regenerate explanation"
          >
            <RefreshCw className={`w-4 h-4 ${loading ? 'animate-spin text-[#005691]' : ''}`} />
          </button>
        </div>
      </div>

      {/* Explanation Content */}
      {loading ? (
        <div className="py-6 flex flex-col items-center justify-center gap-2 text-slate-500">
          <RefreshCw className="w-5 h-5 animate-spin text-[#005691]" />
          <span className="text-xs">
            Querying Gemma 4 with tool calling (get_shortage_forecast)...
          </span>
        </div>
      ) : explanation ? (
        <div className="space-y-3">
          <div className="text-slate-800 leading-relaxed whitespace-pre-line text-xs sm:text-sm">
            {explanation}
          </div>
          <div className="pt-2 border-t border-sky-100 flex items-center justify-between text-[11px] text-slate-500">
            <span className="flex items-center gap-1">
              <ShieldCheck className="w-3.5 h-3.5 text-emerald-600" />
              {provenance ||
                (usedTool
                  ? 'Generated by Gemma 4 via function calling (get_shortage_forecast).'
                  : 'Synthesized by Gemma 4.')}
            </span>
            <span className="font-semibold text-slate-400">Strictly Informational</span>
          </div>
        </div>
      ) : (
        <div className="py-4 text-center">
          <button
            onClick={() => fetchExplanation(lang, false)}
            className="btn-primary text-xs py-1.5 px-3"
          >
            <Sparkles className="w-3.5 h-3.5" />
            Explain this Alert with Gemma 4
          </button>
        </div>
      )}
    </div>
  );
}
